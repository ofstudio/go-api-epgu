package apipgu

// OrderResult - результат отправки заявления методами [Client.OrderPushV2]
// и [Client.OrderPushChunkedV2].
//
// Подробнее см. "Спецификация API ЕПГУ версия 1.15", разделы 2.1.3, 2.1.4
// и Приложение 6. Наличие сообщения о дисклеймере не является ошибкой отправки.
type OrderResult struct {
	OrderId int    // Номер заявления
	Message string // Последнее полученное непустое сообщение о дисклеймере; пустая строка, если сообщений не было
}
